import { writeFileSync } from 'node:fs';
import cloudflare from '@sveltejs/adapter-cloudflare';
import { vitePreprocess } from '@sveltejs/vite-plugin-svelte';

// Cloudflare Pages allows 100 rules in _routes.json. Anything excluded there is
// served as a static file without invoking the Function at all.
const ROUTES_LIMIT = 100;

// Whole trees that are only ever static files. Spending a wildcard on each
// leaves the per-file slots for prerendered pages (newest posts first).
const STATIC_TREES = [
  '/_app/immutable/*',
  '/static/*',
  '/og-fonts/*',
  '/papers/*',
  '/reading/page/*',
  '/photos/page/*',
  '/library/page/*'
];

// The stock adapter fills _routes.json in a fixed order and truncates at the
// limit, so most slots went to paper PDFs and fonts. Rewrite it once the
// adapter is done. Prerendered pages that still don't fit skip rendering
// anyway: the worker hands any path in its prerendered set straight to ASSETS.
function cloudflareWithStaticRoutes() {
  // The stock list is replaced below; keep it minimal so it doesn't warn.
  const base = cloudflare({ routes: { include: ['/*'], exclude: ['<build>'] } });

  return {
    ...base,
    async adapt(builder) {
      await base.adapt(builder);

      const covered = (path) =>
        STATIC_TREES.some((tree) => path.startsWith(tree.slice(0, -1)));
      const files = [
        '/_app/version.json',
        '/favicon.ico',
        ...builder.prerendered.paths.filter((path) => !covered(path))
      ];
      const exclude = [...STATIC_TREES, ...new Set(files)].slice(0, ROUTES_LIMIT - 1);

      // pages_build_output_dir in wrangler.toml.
      writeFileSync(
        '.svelte-kit/cloudflare/_routes.json',
        JSON.stringify({ version: 1, description: 'Generated by svelte.config.js', include: ['/*'], exclude }, null, '\t')
      );
      builder.log.info(
        `_routes.json: ${exclude.length} exclude rules, ${files.length - (exclude.length - STATIC_TREES.length)} prerendered paths left to the worker's static pass-through`
      );
    }
  };
}

/** @type {import('@sveltejs/kit').Config} */
const config = {
  preprocess: vitePreprocess(),
  kit: {
    adapter: cloudflareWithStaticRoutes(),
    prerender: {
      // page.url.origin in prerendered HTML (canonical links, og:image).
      origin: 'https://www.disnetdev.com',
      // A dead internal link in old content shouldn't block a deploy, but a
      // failed render (say, the PDS was unreachable) must: better to keep the
      // last good build than ship pages with nothing on them.
      handleHttpError: ({ status, message }) => {
        if (status === 404) {
          console.warn(message);
          return;
        }
        throw new Error(message);
      },
      // at:// links (publication and record pointers) aren't pages to crawl.
      handleInvalidUrl: ({ href, message }) => {
        if (href.startsWith('at://')) return;
        throw new Error(message);
      }
    }
  }
};

export default config;
